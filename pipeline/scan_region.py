"""LEVEL-UP: scan a whole region for analogs nobody has listed yet.

Lays a grid over a bounding box, fetches climate (NASA POWER) and terrain
(SRTM tiles) for every cell, and writes web/data/scan_cells.js. Add this line
to web/index.html, just after earth_sites.js, and the cells join the ranking
with a "Scan cell" badge:

    <script src="data/scan_cells.js"></script>

Rock type and vegetation are unknown for scan cells, so they score a neutral
0.5 on those features: treat a high-ranking cell as a lead to check in NASA
Worldview, not a finished answer.

Usage:
    python pipeline/scan_region.py --name sahara --bbox 10,18,22,27 --step 1
    (bbox = west,south,east,north in degrees; 1-degree steps = ~110 km cells)

A 12 x 9 degree box at 1-degree steps is 108 cells: about 5-10 minutes the
first time, instant after that thanks to the cache.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))

from fetch_power import climate  # noqa: E402
from fetch_terrain import terrain  # noqa: E402


def frange(a, b, step):
    v = a
    while v <= b + 1e-9:
        yield round(v, 4)
        v += step


def scan(name, west, south, east, north, step, out_path, fetch_climate=climate, fetch_terrain=terrain):
    cells = []
    lats = list(frange(south + step / 2, north, step))
    lons = list(frange(west + step / 2, east, step))
    total = len(lats) * len(lons)
    for i, lat in enumerate(lats):
        for j, lon in enumerate(lons):
            n = i * len(lons) + j + 1
            try:
                c = fetch_climate(lat, lon)
                t = fetch_terrain(lat, lon)
            except Exception as e:  # ocean, missing tiles, network: skip the cell
                print(f"[{n}/{total}] skip {lat},{lon}: {e}")
                continue
            if t["elevation_m"] <= -50 and t["relief_m"] < 5:  # flat and below sea level: probably sea
                continue
            cells.append({
                "id": f"scan-{name}-{lat}-{lon}", "name": f"{name.title()} cell {abs(lat):.1f}°{'N' if lat >= 0 else 'S'} {abs(lon):.1f}°{'E' if lon >= 0 else 'W'}",
                "country": f"Scan: {name}", "lat": lat, "lon": lon, "status": "scan", "known_for": [],
                "program": "Grid scan", "note": "Automatic scan cell. Check it in NASA Worldview before trusting it.",
                "elevation_m": t["elevation_m"], "slope_deg": t["slope_deg"], "relief_m": t["relief_m"], "lava_tube": 0,
                "t_min_c": c["t_min_c"], "t_swing_c": c["t_swing_c"], "t_mean_c": c["t_mean_c"],
                "rock": "", "rock2": "", "ndvi": None, "precip_mm": c["precip_mm"], "ground_ice": c["ground_ice"],
                "src": {"t_min_c": "NASA POWER climatology", "t_swing_c": "NASA POWER climatology", "t_mean_c": "NASA POWER climatology",
                        "precip_mm": "NASA POWER climatology", "ground_ice": "NASA POWER climatology (permafrost rule)",
                        "slope_deg": "SRTM via AWS Terrain Tiles", "relief_m": "SRTM via AWS Terrain Tiles", "elevation_m": "SRTM via AWS Terrain Tiles"},
            })
            print(f"[{n}/{total}] ok {lat},{lon}")
    out_path = pathlib.Path(out_path)
    out_path.write_text("// Generated by pipeline/scan_region.py. Grid cells for the discovery scan.\n"
                        "window.SCAN_CELLS = (window.SCAN_CELLS || []).concat(" + json.dumps(cells) + ");\n", encoding="utf-8")
    print(f"Wrote {len(cells)} cells to {out_path}")
    return cells


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True, help="short region name, e.g. sahara")
    ap.add_argument("--bbox", required=True, help="west,south,east,north in degrees")
    ap.add_argument("--step", type=float, default=1.0)
    ap.add_argument("--out", default=str(ROOT / "web" / "data" / "scan_cells.js"))
    args = ap.parse_args(argv)
    w, s, e, n = (float(v) for v in args.bbox.split(","))
    return scan(args.name, w, s, e, n, args.step, args.out)


if __name__ == "__main__":
    main()

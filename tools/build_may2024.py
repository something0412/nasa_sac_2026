"""Download real May 2024 space weather from NASA DONKI and save it for the game.

Usage:
    python tools/build_may2024.py            # downloads with DEMO_KEY
    python tools/build_may2024.py MY_API_KEY # use your own key from api.nasa.gov

Writes data/may2024.js. The game reads that file, so it never needs the internet.
Note: the DONKI /FLR endpoint on api.nasa.gov returned 404 in Nov 2026, so flare
classes are read from DONKI flare *notifications* instead.
"""
import json
import re
import sys
import urllib.request
from datetime import datetime
from pathlib import Path

KEY = sys.argv[1] if len(sys.argv) > 1 else "DEMO_KEY"
BASE = "https://api.nasa.gov/DONKI/{}?startDate=2024-05-01&endDate=2024-05-31&api_key=" + KEY
OUT = Path(__file__).resolve().parent.parent / "data" / "may2024.js"
T0 = datetime(2024, 5, 1)


def get(endpoint):
    with urllib.request.urlopen(BASE.format(endpoint), timeout=90) as r:
        return json.load(r)


def hours(stamp):
    return round((datetime.strptime(stamp[:16], "%Y-%m-%dT%H:%M") - T0).total_seconds() / 3600, 1)


def rank(cls):
    return {"M": 1, "X": 10}[cls[0]] * float(cls[1:])


def main():
    notes, sep, gst = get("notifications"), get("SEP"), get("GST")

    # Flares: biggest class named in each FLR notification. "M5.0" is only the alert threshold text.
    flares = []
    for e in notes:
        if e["messageType"] != "FLR":
            continue
        classes = [c for c in re.findall(r"\b([MX]\d\.\d)\b", e["messageBody"]) if c != "M5.0"]
        if classes:
            flares.append({"t": e["messageIssueTime"], "h": hours(e["messageIssueTime"]), "cls": max(classes, key=rank)})
    merged = []
    for f in sorted(flares, key=lambda x: x["h"]):
        if merged and f["h"] - merged[-1]["h"] < 1.0:  # same flare reported twice
            if rank(f["cls"]) > rank(merged[-1]["cls"]):
                merged[-1] = f
        else:
            merged.append(f)

    # Solar particle (radiation) storms: group detections less than 10 h apart.
    storms = []
    for e in sorted(sep, key=lambda x: x["eventTime"]):
        h, inst = hours(e["eventTime"]), e["instruments"][0]["displayName"]
        if storms and h - storms[-1]["_last"] < 10:
            storms[-1]["_last"] = h
            storms[-1]["instruments"].add(inst)
        else:
            storms.append({"t": e["eventTime"], "h": h, "_last": h, "instruments": {inst}})
    for s in storms:
        s["strong"] = any(">100 MeV" in i for i in s["instruments"])
        s["instruments"] = sorted(s["instruments"])
        del s["_last"]

    geo = [{"t": g["startTime"], "h": hours(g["startTime"]), "kpMax": max(k["kpIndex"] for k in g["allKpIndex"])} for g in gst]

    data = {
        "source": "NASA DONKI via api.nasa.gov (notifications, SEP, GST), May 2024",
        "missionStartUTC": "2024-05-01T00:00Z",
        "flares": merged,
        "sepStorms": storms,
        "geomagStorms": geo,
    }
    OUT.write_text(
        "// GENERATED by tools/build_may2024.py from NASA DONKI. Do not hand-edit.\n"
        "// The values are real NASA data. Only the script that downloads and formats them was written with help from Claude Code (AI), reviewed by the team.\n"
        "// h = hours since 2024-05-01 00:00 UTC (= mission hour in the historical scenario).\n"
        "window.MAY2024 = " + json.dumps(data, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"{len(merged)} flares, {len(storms)} radiation storms, {len(geo)} geomagnetic storms -> {OUT}")


if __name__ == "__main__":
    main()
